func TestPlanPostgresUpsertUsesReplacementSemantics(t *testing.T) {
	metadata := sinkTableMetadata{
		Columns: []sinkColumnMetadata{
			{Name: "id", Identity: true, IdentityGeneration: "ALWAYS"},
			{Name: "name"},
			{Name: "status", HasDefault: true},
			{Name: "note", Nullable: true},
			{Name: "computed", Generated: true},
		},
		PrimaryKey: []string{"id"},
	}
	document := map[string]interface{}{
		"id":   int32(7),
		"name": "example",
	}
	operation, err := planPostgresUpsert(metadata, document, 3)
	if err != nil {
		t.Fatal(err)
	}
	if !operation.overrideIdentity {
		t.Fatal("expected GENERATED ALWAYS identity override")
	}
	if !reflect.DeepEqual(operation.columns, []string{"id", "name", "note"}) {
		t.Fatalf("columns = %#v", operation.columns)
	}
	if !reflect.DeepEqual(operation.defaultColumns, []string{"status"}) {
		t.Fatalf("default columns = %#v", operation.defaultColumns)
	}
	if !reflect.DeepEqual(operation.values, []interface{}{int32(7), "example", nil}) {
		t.Fatalf("values = %#v", operation.values)
	}
	query := buildUpsertQuery("public.items", metadata.PrimaryKey, operation.columns, operation.defaultColumns, operation.overrideIdentity)
	for _, fragment := range []string{
		`INSERT INTO "public"."items" ("id", "name", "note") OVERRIDING SYSTEM VALUE`,
		`"name" = EXCLUDED."name"`,
		`"note" = EXCLUDED."note"`,
		`"status" = DEFAULT`,
	} {
		if !strings.Contains(query, fragment) {
			t.Fatalf("query %q does not contain %q", query, fragment)
		}
	}
}

func TestPlanPostgresUpsertRejectsInvalidDocuments(t *testing.T) {
	metadata := sinkTableMetadata{
		Columns:    []sinkColumnMetadata{{Name: "id"}, {Name: "required"}},
		PrimaryKey: []string{"id"},
	}
	tests := []struct {
		name     string
		document map[string]interface{}
		contains string
	}{
		{name: "missing key", document: map[string]interface{}{"required": "x"}, contains: `key field "id"`},
		{name: "missing required", document: map[string]interface{}{"id": 1}, contains: `required column "required"`},
		{name: "null required", document: map[string]interface{}{"id": 1, "required": nil}, contains: `cannot be null`},
		{name: "unknown column", document: map[string]interface{}{"id": 1, "required": "x", "extra": true}, contains: `column "extra" does not exist`},
	}
	for _, test := range tests {
		t.Run(test.name, func(t *testing.T) {
			_, err := planPostgresUpsert(metadata, test.document, 0)
			if err == nil || !strings.Contains(err.Error(), test.contains) {
				t.Fatalf("error = %v, want containing %q", err, test.contains)
			}
		})
	}
}

func TestPlanPostgresUpsertRejectsGeneratedPrimaryKey(t *testing.T) {
	_, err := planPostgresUpsert(sinkTableMetadata{
		Columns:    []sinkColumnMetadata{{Name: "id", Generated: true}},
		PrimaryKey: []string{"id"},
	}, map[string]interface{}{"id": 1}, 0)
	if err == nil || !strings.Contains(err.Error(), "generated primary key") {
		t.Fatalf("error = %v", err)
	}
}

func TestPlanPostgresUpsertRejectsSuppliedGeneratedNonKey(t *testing.T) {
	for _, column := range []sinkColumnMetadata{
		{Name: "computed", Generated: true},
		{Name: "generated_id", Identity: true},
	} {
		metadata := sinkTableMetadata{
			Columns:    []sinkColumnMetadata{{Name: "id"}, column},
			PrimaryKey: []string{"id"},
		}
		_, err := planPostgresUpsert(metadata, map[string]interface{}{
			"id":        int64(1),
			column.Name: "source value",
		}, 0)
		if err == nil || !strings.Contains(err.Error(), fmt.Sprintf(`column %q is generated by the destination`, column.Name)) {
			t.Fatalf("expected generated-column error for %q, got %v", column.Name, err)
		}
	}
}

func TestPlanPostgresUpsertAllowsOmittedGeneratedNonKey(t *testing.T) {
	metadata := sinkTableMetadata{
		Columns: []sinkColumnMetadata{
			{Name: "id"},
			{Name: "generated_id", Identity: true},
		},
		PrimaryKey: []string{"id"},
	}
	if _, err := planPostgresUpsert(metadata, map[string]interface{}{"id": int64(1)}, 0); err != nil {
		t.Fatalf("unexpected error for omitted generated column: %v", err)
	}
}

func TestWriteUpdatesUnknownIsNoop(t *testing.T) {
	c := &conn{sinkMetadata: map[string]sinkTableMetadata{
		"public.items": {Columns: []sinkColumnMetadata{{Name: "id"}}, PrimaryKey: []string{"id"}},
	}}
	_, err := c.WriteUpdates(context.Background(), connect.NewRequest(&adiomv1.WriteUpdatesRequest{
		Namespace: "public.items",
		Updates:   []*adiomv1.Update{{Type: adiomv1.UpdateType_UPDATE_TYPE_UNKNOWN}},
	}))
	if err != nil {
		t.Fatal(err)
	}
}

func TestPostgresSinkRejectsPartialResultsAndUpdates(t *testing.T) {
	c := &conn{sinkMetadata: map[string]sinkTableMetadata{
		"public.items": {Columns: []sinkColumnMetadata{{Name: "id"}}, PrimaryKey: []string{"id"}},
	}}
	_, err := c.WriteData(context.Background(), connect.NewRequest(&adiomv1.WriteDataRequest{PartialWriteResults: true}))
	if connect.CodeOf(err) != connect.CodeInvalidArgument {
		t.Fatalf("WriteData error = %v", err)
	}
	_, err = c.WriteUpdates(context.Background(), connect.NewRequest(&adiomv1.WriteUpdatesRequest{
		Namespace: "public.items",
		Updates:   []*adiomv1.Update{{Type: adiomv1.UpdateType_UPDATE_TYPE_PARTIAL_UPDATE}},
	}))
	if connect.CodeOf(err) != connect.CodeInvalidArgument {
		t.Fatalf("WriteUpdates error = %v", err)
	}
}

func TestPostgresSinkReportsMalformedInputAsInvalidArgument(t *testing.T) {
	c := &conn{
		sinkMetadata: map[string]sinkTableMetadata{
			"public.items": {Columns: []sinkColumnMetadata{{Name: "id"}}, PrimaryKey: []string{"id"}},
		},
		bsonRegistry: NewBSONRegistry(),
	}
	_, err := c.WriteData(context.Background(), connect.NewRequest(&adiomv1.WriteDataRequest{
		Namespace: "public.items",
		Data:      [][]byte{{0x01, 0x02}},
	}))
	if connect.CodeOf(err) != connect.CodeInvalidArgument {
		t.Fatalf("WriteData error = %v", err)
	}
	_, err = c.WriteUpdates(context.Background(), connect.NewRequest(&adiomv1.WriteUpdatesRequest{
		Namespace: "public.items",
		Updates:   []*adiomv1.Update{{Type: adiomv1.UpdateType_UPDATE_TYPE_DELETE}},
	}))
	if connect.CodeOf(err) != connect.CodeInvalidArgument {
		t.Fatalf("WriteUpdates error = %v", err)
	}
}
